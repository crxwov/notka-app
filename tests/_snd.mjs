// Экран «Звук и загрузки».   node tests/_snd.mjs
import { launch } from "./cdp.mjs";
const BASE = "http://127.0.0.1:8099";
const b = await launch({ dir: "C:/Users/leksik/Documents/Notka/tests/shots", port: 9377 });
const mk = (t, a, v) => ({ id: `youtube_music_${v}`, source: "youtube_music", sourceId: v, title: t, artist: a, duration: 240, artwork: `https://i.ytimg.com/vi/${v}/hqdefault.jpg` });
const tr = [mk("Yellow", "Coldplay", "yKNxeF4KMsY"), mk("Creep", "Radiohead", "XFkzRNyygfk")];
let failed = 0;
const check = (n, ok, x = "") => { if (!ok) failed++; console.log(ok ? "PASS" : "FAIL", n, x); };
await b.goto(`${BASE}/health`);
await b.eval(`localStorage.clear(); localStorage.setItem("notka_state_v2", ${JSON.stringify(JSON.stringify({ favorites: tr, onboardingSeenV2: true, recent: tr, playlists: [], settings: {} }))}); true`);
await b.goto(`${BASE}/app/`);
await b.waitFor("document.body.dataset.screen !== 'splash'", 8000, "x");
await b.click("#home-avatar-btn"); await b.click("#menu-sound"); await b.sleep(1200);
check("opens", (await b.eval("document.body.dataset.screen")) === "sound");
check("off by default", (await b.eval("document.getElementById('crossfade-value').textContent")) === "Выкл");
await b.shot("snd-a");
await b.eval("(() => { const s = document.getElementById('crossfade-slider'); s.value = 6; s.dispatchEvent(new Event('input', { bubbles: true })); return true; })()");
await b.sleep(300);
check("value shows", (await b.eval("document.getElementById('crossfade-value').textContent")) === "6" && (await b.eval("document.getElementById('crossfade-unit').textContent")) === "сек");
check("saved", (await b.eval("(JSON.parse(localStorage.getItem('notka_state_v2')).settings || {}).crossfade")) === 6);
await b.shot("snd-b");
await b.eval("(() => { const s = document.getElementById('crossfade-slider'); s.value = 12; s.dispatchEvent(new Event('input', { bubbles: true })); return true; })()");
await b.sleep(200);
await b.shot("snd-c");
await b.click("#sound-back-btn"); await b.sleep(500);
check("profile shows it", (await b.eval("document.getElementById('pf-sub-sound').textContent")).includes("12"), await b.eval("document.getElementById('pf-sub-sound').textContent"));
check("no errors", b.errors.filter((e) => !/Haptic/.test(e)).length === 0, b.errors.join("|").slice(0, 200));
await b.close();
process.exit(failed ? 1 : 0);
