// Итоги: карточки месяца и всего времени, картинка для отправки; без Плюса экран не открывается.
//   node tests/recap.mjs   (нужен tests/serve_local.py)
import { launch } from "./cdp.mjs";
const BASE = "http://127.0.0.1:8099";
const b = await launch({ dir: "C:/Users/leksik/Documents/Notka/tests/shots", port: 9378 });
let bad = 0;
const check = (name, ok, extra = "") => { console.log((ok ? "PASS " : "FAIL ") + name + " " + extra); if (!ok) bad++; };
const search = async (q) => (await (await fetch(`${BASE}/search?q=${encodeURIComponent(q)}`)).json()).results || [];
const tracks = [...(await search("Группа крови Кино")), ...(await search("Miyagi Minor"))].filter((t) => t.artwork).slice(0, 6);
const today = new Date();
const key = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, "0")}-${String(today.getDate()).padStart(2, "0")}`;
const slim = (t) => ({ id: t.id, source: t.source, sourceId: t.sourceId, title: t.title, artist: t.artist, duration: t.duration, artwork: t.artwork });
const t = {}, a = {}, dayT = {}, dayA = {};
tracks.forEach((x, i) => {
  t[x.id] = { track: slim(x), plays: 9 - i, seconds: 2400 - i * 300 };
  dayT[x.id] = [9 - i, 2400 - i * 300];
  const n = x.artist || "Неизвестный";
  a[n] = a[n] || { plays: 0, seconds: 0 };
  a[n].plays += 9 - i; a[n].seconds += 2400 - i * 300;
  dayA[n] = dayA[n] || [0, 0];
  dayA[n][0] += 9 - i; dayA[n][1] += 2400 - i * 300;
});
const total = Object.values(t).reduce((s, x) => s + x.seconds, 0);
const seed = { favorites: tracks, recent: tracks.slice(0, 3), onboardingSeenV2: true, accountName: "Лёша", playlists: [], settings: {},
  listens: { seconds: total, plays: 40, tracks: t, artists: a, days: { [key]: { s: total, p: 40, t: dayT, a: dayA } } } };
await b.goto(`${BASE}/health`);
await b.eval(`localStorage.clear(); localStorage.setItem("notka_state_v2", ${JSON.stringify(JSON.stringify(seed))}); true`);
await b.goto(`${BASE}/app/`);
await b.waitFor("!!document.body && document.body.dataset.screen !== 'splash'", 8000, "x");
await b.sleep(800);
const open = async () => { await b.click("#home-avatar-btn"); await b.sleep(500); await b.click("#menu-stats"); await b.sleep(600); };
await open();
await b.click("#stats-recap-btn"); await b.sleep(700);
check("without Плюс the recap sends you to the Плюс page", (await b.eval("document.body.dataset.screen")) === "plus");
await b.eval("localStorage.setItem('notka_plus_local','1'); true");
await b.goto(`${BASE}/app/`);
await b.waitFor("!!document.body && document.body.dataset.screen !== 'splash'", 8000, "x");
await b.sleep(800);
await open();
await b.click("#stats-recap-btn"); await b.sleep(1200);
check("with Плюс the recap opens", (await b.eval("document.body.dataset.screen")) === "recap");
check("four cards for the month", (await b.eval("document.querySelectorAll('#recap-deck .rcp-card').length")) === 4);
check("the first card shows the real minutes", await b.eval(`document.querySelector('#recap-deck .rcp-num').textContent.replace(/\\s/g, '') === String(${Math.round(total / 60)})`));
await b.shot("recap-1");
await b.eval("document.getElementById('recap-deck').scrollTo({ left: 400, behavior: 'instant' }); true"); await b.sleep(500);
await b.shot("recap-2");
await b.eval("document.getElementById('recap-deck').scrollTo({ left: 700, behavior: 'instant' }); true"); await b.sleep(500);
await b.shot("recap-3");
await b.eval("document.getElementById('recap-deck').scrollTo({ left: 99999, behavior: 'instant' }); true"); await b.sleep(500);
await b.shot("recap-4");
check("the dots follow the swipe", await b.eval("document.querySelectorAll('#recap-dots i')[3].classList.contains('is-on')"));
await b.click("#recap-share-btn"); await b.sleep(3500);
const shared = await b.eval("(() => { const m = document.getElementById('recap-modal'); const i = document.getElementById('recap-preview'); return { open: m.classList.contains('open') || getComputedStyle(m).display !== 'none', w: i.naturalWidth, h: i.naturalHeight }; })()");
check("the card turns into a 1080x1350 picture", shared.w === 1080 && shared.h === 1350, JSON.stringify(shared));
await b.eval("document.getElementById('recap-preview').scrollIntoView(); true");
await b.shot("recap-modal");
await b.click("#recap-modal-close"); await b.sleep(400);
await b.click('#recap-periods [data-period="all"]'); await b.sleep(600);
check("«Всё время» also has cards", (await b.eval("document.querySelectorAll('#recap-deck .rcp-card').length")) >= 3);
console.log(bad ? "FAILED" : "ALL PASS");
process.exit(bad ? 1 : 0);
